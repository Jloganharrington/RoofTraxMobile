function buildSummaryOfFindingsPrompt(
  brief: string,
  approvedSections: Map<string, string>,
): string {
  const sectionTexts: string[] = [];
  const order: Array<[string, string]> = [
    ['findings', 'Damage Findings'],
    ['causation', 'Causation'],
    ['detriment_application', 'Detriment Application'],
    ['rap_narrative', 'Repairability Protocol Narrative'],
    ['estimate_justifications', 'Estimate Justifications'],
  ];
  for (const [key, label] of order) {
    const html = approvedSections.get(key);
    if (html) {
      // Strip HTML tags to plain text for the prompt
      const text = html.replace(/<[^>]+>/g, ' ').replace(/\s+/g, ' ').trim().slice(0, 2000);
      sectionTexts.push(`${label.toUpperCase()}:\n${text}`);
    }
  }

  return `You are writing the Summary of Findings section of a forensic roofing inspection report.

${CONTRACTOR_LANE_POLICY}

Synthesize the following approved section content into a concise executive summary of 3–5 paragraphs. This section MUST:
- Only summarize what the approved sections document — do not introduce new analysis
- Present findings in a clear, professional narrative flow
- Use attributable phrasing throughout ("The inspection documentation identifies…")

APPROVED SECTIONS TO SYNTHESIZE:
${sectionTexts.join('\n\n---\n\n')}

PROPERTY CONTEXT:
${brief.split('\n').slice(0, 10).join('\n')}

Return ONLY a valid HTML fragment (no wrapper tags, no markdown).`;
}

