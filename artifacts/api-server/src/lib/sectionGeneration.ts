export interface StandardsEntryInput {
  entryKey: string;
  verificationStatus: string;
  version: number;
  verifiedAt?: Date | null;
  /** True for entries whose provision text is human-authored under a licensed
   * standard (e.g. IICRC S500/S520) and must not be reproduced by the AI
   * prompt. The generation worker must filter these out of prompt context and
   * emit a citation placeholder token for human completion. */
  humanEnteredProvisionsOnly?: boolean;
}

export interface BoilerplateVersionInput {
  sectionKey: string;
  version: number;
}

export interface AhjPackVersionInput {
  packType: string;
  version: number;
}

export interface SectionGenerationInput {
  inspectionId: string;
  sectionType: GeneratableSectionType;
  inspection: Record<string, unknown>;
  children: Parameters<typeof buildFieldBrief>[1] & {
    testSquares?: { id: string }[];
    testSquareHits?: { hitType?: string | null }[];
  };
  detrimentEntries: DetrimentEntryInput[];
  approvedSections: Map<string, string>; // sectionType → contentHtml (for DAG-last)
  standardsEntries: StandardsEntryInput[];
  boilerplateVersions: BoilerplateVersionInput[];
  ahjPackVersions: AhjPackVersionInput[];
}

export interface SectionGenerationResult {
  contentHtml: string;
  lintResult: LintResult;
  rapMode: string | null;
  libraryVersionSnapshot: {
    bpVersions: Record<string, number>;
    ahjPackVersions: Record<string, number>;
    standardsEntryKeys: string[];
    generatedAt: string;
  };
}

// ---------------------------------------------------------------------------
// Main generation function
// ---------------------------------------------------------------------------

export async function generateSectionContent(
  input: SectionGenerationInput,
): Promise<SectionGenerationResult> {
  const {
    sectionType,
    inspection,
    children,
    detrimentEntries,
    approvedSections,
    standardsEntries,
    boilerplateVersions,
    ahjPackVersions,
  } = input;

  const brief = buildFieldBrief(inspection, children);
  const conditionSet = buildFieldConditionSet(inspection, children);
  const filteredDetriments = filterDetrimentEntries(detrimentEntries, conditionSet);

  // ── IICRC filter ──────────────────────────────────────────────────────────
  // Partition standards entries: IICRC-licensed entries must never be fed to
  // the AI as citation text. Instead we build a directive that instructs the
  // AI to emit a placeholder token wherever it would cite those standards.
  const iicrcEntryKeys = standardsEntries
    .filter((e) => e.humanEnteredProvisionsOnly === true)
    .map((e) => e.entryKey);
  const iicrcDirective = buildIicrcDirectiveBlock(iicrcEntryKeys);

  let rapMode: string | null = null;
  const ra = inspection.repairabilityAssessment as StoredRepairabilityAssessment | null;
  if (ra) {
    const rapData = extractRap(ra);
    if (rapData) {
      rapMode = rapData.selection?.mode ?? null;
    }
  }

  // Build section-specific prompt, then append the IICRC directive when needed.
  let prompt: string;
  switch (sectionType) {
    case 'findings':
      prompt = buildFindingsPrompt(brief);
      break;

    case 'causation':
      prompt = buildCausationPrompt(brief, filteredDetriments);
      break;

    case 'detriment_application':
      prompt = buildDetrimentApplicationPrompt(brief, filteredDetriments);
      break;

    case 'rap_narrative': {
      const rapBrief: string[] = [];
      let hasRap = false;
      let hasVap = false;
      let hasAsp = false;
      if (ra) {
        const rapData = extractRap(ra);
        if (rapData) {
          hasRap = true;
          for (const line of rapScorecardBriefLines(computeRapScorecard(rapData), rapData.selection)) {
            rapBrief.push(line);
          }
        }
        const vapData = extractVap(ra);
        if (vapData) {
          hasVap = true;
          for (const line of vapScorecardBriefLines(computeVapScorecard(vapData))) {
            rapBrief.push(line);
          }
        }
        const aspData = extractAsp(ra);
        if (aspData) {
          hasAsp = true;
          for (const line of aspScorecardBriefLines(computeAspScorecard(aspData))) {
            rapBrief.push(line);
          }
        }
      }
      prompt = buildRepairabilityProtocolNarrativePrompt(brief, rapMode, rapBrief, {
        hasRap,
        hasVap,
        hasAsp,
      });
      break;
    }

    case 'estimate_justifications': {
      const estimate = inspection.estimate as
        | { lines?: Array<{ description?: string; quantity?: number; unit?: string | null; unitPriceCents?: number; isAdder?: boolean }> }
        | null;
      const lines = (estimate?.lines ?? []).map((l) => ({
        description: l.description ?? 'Line item',
        qty: l.quantity ?? 1,
        unit: l.unit ?? null,
        unitPriceCents: l.unitPriceCents ?? 0,
        isAdder: l.isAdder ?? false,
      }));
      prompt = buildEstimateJustificationsPrompt(brief, lines);
      break;
    }

    case 'summary_of_findings':
      prompt = buildSummaryOfFindingsPrompt(brief, approvedSections);
      break;

    case 'closing_statement': {
      const flags = inspection.triggerFlags as Record<string, string> | null;
      prompt = buildClosingStatementPrompt(brief, flags);
      break;
    }

    default:
      throw new Error(`Unknown section type: ${sectionType as string}`);
  }

  // Append IICRC directive after the main prompt body (before the final
  // "Return ONLY…" instruction so the model reads it last).
  if (iicrcDirective) {
    prompt = prompt.replace(
      /\nReturn ONLY a valid HTML fragment \(no wrapper tags, no markdown\)\./,
      `\n${iicrcDirective}\n\nReturn ONLY a valid HTML fragment (no wrapper tags, no markdown).`,
    );
    // If the replace didn't match (shouldn't happen), just append.
    if (!prompt.includes(iicrcDirective)) {
      prompt = `${prompt}\n\n${iicrcDirective}`;
    }
  }

  // Call Gemini
  const response = await geminiAi.models.generateContent({
    model: 'gemini-2.5-flash',
    contents: [{ role: 'user', parts: [{ text: prompt }] }],
    config: { maxOutputTokens: 4096 },
  });

  const rawHtml = (response.text ?? '').replace(/^```html\s*/i, '').replace(/\s*```$/, '').trim();

  // Sanitize LLM output — treat as untrusted to prevent prompt-injection XSS.
  // Placeholder tokens ({{IICRC_CITATION_PLACEHOLDER:...}}) are plain text
  // inside HTML text nodes and survive sanitization unchanged.
  const contentHtml = sanitizeSectionHtml(rawHtml);

  // Contractor-lane lint
  const lintInputs: LintFragmentInput[] = [
    {
      fragmentRef: `section.${sectionType}`,
      contentClass: 'construction_fact',
      text: contentHtml,
      isHtml: true,
    },
  ];
  const lintResult = lintReportFragments(lintInputs);

  // ── IICRC placeholder lint findings ────────────────────────────────────────
  // Any unfilled {{IICRC_CITATION_PLACEHOLDER:KEY}} token in the sanitized
  // output surfaces as a `needs_review` lint finding. The UI uses these to
  // block the Approve button until the reviewer fills in every placeholder.
  const unfilledKeys = extractUnfilledIicrcPlaceholders(contentHtml);
  for (const key of unfilledKeys) {
    lintResult.findings.push({
      fragmentRef: `section.${sectionType}`,
      ruleId: 'iicrc_citation_unfilled',
      matchedText: `{{IICRC_CITATION_PLACEHOLDER:${key}}}`,
      severity: 'needs_review',
    });
    if (lintResult.lintStatus === 'passed') {
      lintResult.lintStatus = 'needs_review';
    }
  }

  // Build library version snapshot for auditability
  const bpVersions: Record<string, number> = {};
  for (const bp of boilerplateVersions) bpVersions[bp.sectionKey] = bp.version;

  const ahjPackVersionsRecord: Record<string, number> = {};
  for (const p of ahjPackVersions) ahjPackVersionsRecord[p.packType] = p.version;

  // Collect standards entry keys referenced in the generated content.
  // Include both heuristic-matched keys from normal entries AND IICRC placeholder
  // keys (which appear as tokens, not as the raw key string in the HTML).
  const referencedStandardsKeys = standardsEntries
    .filter(
      (e) =>
        rawHtml.toLowerCase().includes(e.entryKey.toLowerCase()) ||
        (e.humanEnteredProvisionsOnly === true && unfilledKeys.includes(e.entryKey)),
    )
    .map((e) => e.entryKey);

  return {
    contentHtml,
    lintResult,
    rapMode,
    libraryVersionSnapshot: {
      bpVersions,
      ahjPackVersions: ahjPackVersionsRecord,
      standardsEntryKeys: referencedStandardsKeys,
      generatedAt: new Date().toISOString(),
    },
  };
}

// ---------------------------------------------------------------------------
// Section assembly — for the compile route to build the combined HTML
// ---------------------------------------------------------------------------

const SECTION_LABELS: Record<string, string> = {
  findings: 'Damage Findings',
  causation: 'Causation Analysis',
  detriment_application: 'Detriment Application',
  // The persisted key is retained for backwards compatibility, but this
  // narrative can cover RAP, VAP, ASP, or a documented combination.
  rap_narrative: 'Repairability Protocol Narrative',
  estimate_justifications: 'Estimate Justifications',
  summary_of_findings: 'Summary of Findings',
  closing_statement: 'Closing Statement',
};

const SECTION_ORDER: string[] = [
  'findings',
  'causation',
  'detriment_application',
  'rap_narrative',
  'estimate_justifications',
  'summary_of_findings',
  'closing_statement',
];

export interface LockedSectionRow {
  sectionType: string;
  contentHtml: string | null;
  lockedAt: Date | null;
  lockedBy: string | null;
  libraryVersionSnapshot: unknown;
}

/**
 * Assembles locked section content into a single HTML document with a TOC.
 * Two-pass: collect section headings, then build TOC block, then assemble body.
 */
export function assembleSectionHtml(lockedSections: LockedSectionRow[]): string {
  const byType = new Map(lockedSections.map((s) => [s.sectionType, s]));

  // First pass: collect sections in order
  const sectionBlocks: Array<{ id: string; label: string; html: string }> = [];
  for (const key of SECTION_ORDER) {
    const row = byType.get(key);
    if (!row || !row.contentHtml) continue;
    sectionBlocks.push({
      id: `section-${key.replace(/_/g, '-')}`,
      label: SECTION_LABELS[key] ?? key,
      html: row.contentHtml,
    });
  }

  if (sectionBlocks.length === 0) return '';

  // Second pass: build TOC
  const tocItems = sectionBlocks
    .map((b) => `<li><a href="#${b.id}">${b.label}</a></li>`)
    .join('\n  ');
  const toc = `<nav class="section-toc" aria-label="Table of Contents">
  <h2>Contents</h2>
  <ol>
  ${tocItems}
  </ol>
</nav>`;

  // Assemble body with anchor IDs
  const body = sectionBlocks
    .map(
      (b) =>
        `<section id="${b.id}" class="report-section">
<h2>${b.label}</h2>
${b.html}
</section>`,
    )
    .join('\n\n');

  return `${toc}\n\n${body}`;
}
