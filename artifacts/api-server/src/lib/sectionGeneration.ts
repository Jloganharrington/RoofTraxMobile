// ---------------------------------------------------------------------------
// Field condition set — maps field record facts to condition code strings
// used for applicability filtering of detriment entries.
// ---------------------------------------------------------------------------

export function buildFieldConditionSet(
  inspection: Record<string, unknown>,
  children: {
    testSquares?: { id?: string }[];
    damageInstances?: { id?: string; slopeId?: string | null; instanceType?: string | null }[];
    slopes?: { id?: string; damagePresent?: boolean | null; materialType?: string | null }[];
    sidingFacets?: { wrbPresent?: boolean | null; damaged?: boolean | null }[];
  },
): Set<string> {
  const conditions = new Set<string>();

  if (inspection.roofDamageFound) conditions.add('roof_damage_present');
  if (inspection.sidingDamageFound) conditions.add('siding_damage_present');
  if (inspection.interiorDamageFound) conditions.add('interior_damage_present');
  if (inspection.collateralDamageFound) conditions.add('collateral_damage_present');

  const storm = inspection.stormConfirmedRef as { type?: string } | null;
  if (storm?.type === 'hail') conditions.add('hail_peril');
  if (storm?.type === 'wind') conditions.add('wind_peril');
  if (storm?.type === 'tornado') conditions.add('tornado_peril');

  const tr = inspection.temporaryRepairs as
    | { performed?: boolean; openings?: boolean }
    | null;
  if (tr?.performed) conditions.add('mitigation_performed');
  if (tr?.openings) conditions.add('created_opening');

  const ra = inspection.repairabilityAssessment as StoredRepairabilityAssessment | null;
  if (ra) {
    if (ra.version === 3) {
      const v3 = ra as unknown as { warranted?: string; systems?: string[] };
      if (v3.warranted === 'yes') conditions.add('rap_warranted');
      else conditions.add('rap_not_warranted');
    }
    const rapData = extractRap(ra);
    if (rapData) {
      const selMode = rapData.selection?.mode ?? null;
      if (selMode === 'fallback_slope') conditions.add('rap_fallback_slope');
      if (selMode === 'damaged_target') conditions.add('rap_damaged_target');
    }
  }

  if ((children.testSquares ?? []).length > 0) conditions.add('test_squares_present');
  if ((children.damageInstances ?? []).length > 0) conditions.add('damage_instances_present');

  const slopeMaterials = (children.slopes ?? [])
    .map((s) => (s.materialType ?? '').toLowerCase());
  if (slopeMaterials.some((m) => m.includes('asphalt') || m.includes('shingle')))
    conditions.add('asphalt_shingle_material');
  if (slopeMaterials.some((m) => m.includes('metal'))) conditions.add('metal_material');
  if (slopeMaterials.some((m) => m.includes('tile'))) conditions.add('tile_material');

  const estimate = inspection.estimate as { lines?: Array<{ description?: string; categoryCode?: string }> } | null;
  const hasDeck = estimate?.lines?.some(
    (l) =>
      (l.description ?? '').toLowerCase().includes('deck') ||
      (l.categoryCode ?? '').toLowerCase().includes('deck'),
  );
  if (hasDeck) conditions.add('deck_replacement_in_scope');

  if (inspection.interiorDamageFound) conditions.add('interior_scope_present');

  const sidingFacets = children.sidingFacets ?? [];
  if (sidingFacets.some((facet) => facet.wrbPresent === false)) {
    conditions.add('wrb_absent');
  } else if (sidingFacets.length > 0 && sidingFacets.every((facet) => facet.wrbPresent === true)) {
    conditions.add('wrb_present');
  } else if (sidingFacets.some((facet) => facet.damaged === true && facet.wrbPresent == null)) {
    conditions.add('wrb_undetermined');
  }

  const pp = inspection.propertyProfile as
    | { structureType?: string; garageAttached?: boolean }
    | null;
  if (pp?.garageAttached) conditions.add('garage_attached');

  return conditions;
}

/**
 * Applicability gate — filter detriment entries to those whose
 * `applicabilityConditions` are ALL present in the field record condition set.
 * This is a code check, not a prompt instruction.
 */
export function filterDetrimentEntries<T extends { applicabilityConditions: unknown }>(
  entries: T[],
  conditionSet: Set<string>,
): T[] {
  return entries.filter((entry) => {
    const conditions = (entry.applicabilityConditions as string[] | null) ?? [];
    if (conditions.length === 0) return true; // no conditions = universal applicability
    return conditions.every((c) => conditionSet.has(c));
  });
}

// ---------------------------------------------------------------------------
// HTML sanitiser for AI-generated section fragments
// ---------------------------------------------------------------------------
// <a> and <img> are intentionally excluded — section content is LLM output,
// not user-controlled HTML.  External links and embeds must not be injected.
// For user-supplied templates (which allow <a>/<img>), use sanitizeTemplateHtml
// from lib/htmlSanitize.ts instead.
// ---------------------------------------------------------------------------

function sanitizeSectionHtml(raw: string): string {
  return sanitizeHtml(raw, {
    allowedTags: [
      'h2', 'h3', 'h4',
      'p', 'br', 'strong', 'em', 'b', 'i',
      'ul', 'ol', 'li',
      'table', 'thead', 'tbody', 'tfoot', 'tr', 'th', 'td',
      'span', 'div', 'section',
    ],
    allowedAttributes: {
      '*': ['class', 'id', 'style'],
      'td': ['colspan', 'rowspan'],
      'th': ['colspan', 'rowspan', 'scope'],
    },
    allowedStyles: {
      '*': {
        color: [/^[a-zA-Z0-9#(), .%]+$/],
        'background-color': [/^[a-zA-Z0-9#(), .%]+$/],
        'font-size': [/^[\d.]+(%|px|em|rem|pt)$/],
        'font-weight': [/^(bold|normal|\d+)$/],
        'text-align': [/^(left|right|center|justify)$/],
        padding: [/^[\d. px%]+$/],
        margin: [/^[\d. px%]+$/],
        border: [/^[\d. pxsolid#a-zA-Z]+$/],
        'border-radius': [/^[\d.]+(%|px|em|rem)$/],
        opacity: [/^[\d.]+$/],
        display: [/^(block|inline|flex|grid|table|table-row|table-cell|none)$/],
        'vertical-align': [/^(top|middle|bottom|baseline)$/],
      },
    },
    disallowedTagsMode: 'discard',
  });
}

