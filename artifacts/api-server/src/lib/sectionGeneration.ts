function buildFindingsPrompt(brief: string): string {
  return `You are writing the Damage Findings section of a forensic roofing inspection report.

${CONTRACTOR_LANE_POLICY}

Based on the field record below, produce an HTML fragment describing the documented damage findings per area. Use <h3> for area headings (e.g. "Roof System", "Siding", "Interior / Attic", "Collateral"). Under each heading, use <ul><li> items for individual findings. Each finding should state only what the field record documents — do not speculate or extrapolate.

Use only attributable phrasing:
- "The inspection documentation identifies…"
- "Photographs in this package depict…"
- "The field record documents…"

Return ONLY a valid HTML fragment. No <html>, <head>, <body> wrapper. No markdown fences. No preamble.

FIELD RECORD:
${brief}`;
}

function buildCausationPrompt(
  brief: string,
  filteredDetriments: Array<{
    entryKey: string;
    statement: string;
    requiredSupport?: string | null;
    limitation?: string | null;
  }>,
): string {
  const detrimentBlock =
    filteredDetriments.length === 0
      ? '(No applicable detriment entries for this field record.)'
      : filteredDetriments
          .map(
            (d) =>
              `Entry ${d.entryKey}:\n  Statement: ${d.statement}${d.requiredSupport ? `\n  Required support: ${d.requiredSupport}` : ''}${d.limitation ? `\n  Limitation: ${d.limitation}` : ''}`,
          )
          .join('\n\n');

  return `You are writing the Causation section of a forensic roofing inspection report.

${CONTRACTOR_LANE_POLICY}

The following detriment entries have been pre-filtered by an applicability check against the field record conditions. Apply ONLY these entries — do not reference conditions or detriments not supported by the field record. For each entry, write prose connecting the documented field conditions to the claimed detriment mechanism. Cite only what the record supports.

APPLICABLE DETRIMENT ENTRIES:
${detrimentBlock}

FIELD RECORD:
${brief}

Return ONLY a valid HTML fragment (no wrapper tags, no markdown).`;
}

function buildDetrimentApplicationPrompt(
  brief: string,
  filteredDetriments: Array<{
    entryKey: string;
    statement: string;
    requiredSupport?: string | null;
    limitation?: string | null;
  }>,
): string {
  const detrimentBlock =
    filteredDetriments.length === 0
      ? '(No applicable detriment entries for this field record.)'
      : filteredDetriments
          .map(
            (d) =>
              `Entry ${d.entryKey}:\n  Statement: ${d.statement}${d.requiredSupport ? `\n  Required support: ${d.requiredSupport}` : ''}${d.limitation ? `\n  Limitation: ${d.limitation}` : ''}`,
          )
          .join('\n\n');

  return `You are writing the Detriment Application section of a forensic roofing inspection report.

${CONTRACTOR_LANE_POLICY}

For each applicable detriment entry below:
1. Confirm the required support documentation is present in the field record (state which record element satisfies it)
2. Render the detriment statement in professional report prose, attributed to the documented record
3. Note any limitations

Present each entry as a titled subsection (<h3> with the entry key) followed by prose.

APPLICABLE DETRIMENT ENTRIES:
${detrimentBlock}

FIELD RECORD:
${brief}

Return ONLY a valid HTML fragment (no wrapper tags, no markdown).`;
}

function buildRapNarrativePrompt(
  brief: string,
  rapMode: string | null,
  rapBriefLines: string[],
): string {
  const modeInstruction =
    rapMode === 'fallback_slope'
      ? `The RAP was performed using the FALLBACK-SLOPE variant (the target slope did not receive a simulated repair attempt; a representative fallback slope was used). Render the narrative reflecting the fallback-slope protocol.`
      : rapMode === 'damaged_target'
        ? `The RAP was performed using the DAMAGED-TARGET variant (the simulated repair was applied directly to the storm-damaged area). Render the narrative reflecting the damaged-target protocol.`
        : `Describe the Repair Attempt Protocol record as documented.`;

  return `You are writing the Repair Attempt Protocol Narrative section of a forensic roofing inspection report.

${CONTRACTOR_LANE_POLICY}

${modeInstruction}

Write professional prose describing the RAP as conducted — the method applied, the conditions, the result. Do not add conclusions beyond what the scorecard documents. Use <p> for paragraphs.

RAP SCORECARD DATA:
${rapBriefLines.join('\n')}

FIELD RECORD CONTEXT:
${brief}

Return ONLY a valid HTML fragment (no wrapper tags, no markdown).`;
}

function buildEstimateJustificationsPrompt(
  brief: string,
  estimateLines: Array<{
    description: string;
    qty: number;
    unit: string | null;
    unitPriceCents: number;
    isAdder: boolean;
  }>,
): string {
  const lineBlock =
    estimateLines.length === 0
      ? '(No estimate lines recorded.)'
      : estimateLines
          .map(
            (l, i) =>
              `Line ${i + 1}: ${l.description} — ${l.qty} ${l.unit ?? 'EA'} @ $${(l.unitPriceCents / 100).toFixed(2)}${l.isAdder ? ' [adder]' : ''}`,
          )
          .join('\n');

  return `You are writing the Estimate Justifications section of a forensic roofing inspection report.

${CONTRACTOR_LANE_POLICY}

For each estimate line item below, write 1–2 sentences explaining why this item is required based on the field record. Reference only what the documented conditions support. Use the exact line description as the heading for each justification block.

Format each justification as: <div class="est-justification"><h4>[Line description]</h4><p>[Justification]</p></div>

ESTIMATE LINES:
${lineBlock}

FIELD RECORD CONTEXT:
${brief}

Return ONLY a valid HTML fragment (no wrapper tags, no markdown).`;
}

function buildSummaryOfFindingsPrompt(
  brief: string,
  approvedSections: Map<string, string>,
): string {
  const sectionTexts: string[] = [];
  const order: Array<[string, string]> = [
    ['findings', 'Damage Findings'],
    ['causation', 'Causation'],
    ['detriment_application', 'Detriment Application'],
    ['rap_narrative', 'RAP Narrative'],
    ['estimate_justifications', 'Estimate Justifications'],
  ];
  for (const [key, label] of order) {
    const html = approvedSections.get(key);
    if (html) {
      // Strip HTML tags to plain text for the prompt
      const text = html.replace(/<[^>]+>/g, ' ').replace(/\s+/g, ' ').trim().slice(0, 2000);
      sectionTexts.push(`${label.toUpperCase()}:\n${text}`);
    }
  }

  return `You are writing the Summary of Findings section of a forensic roofing inspection report.

${CONTRACTOR_LANE_POLICY}

Synthesize the following approved section content into a concise executive summary of 3–5 paragraphs. This section MUST:
- Only summarize what the approved sections document — do not introduce new analysis
- Present findings in a clear, professional narrative flow
- Use attributable phrasing throughout ("The inspection documentation identifies…")

APPROVED SECTIONS TO SYNTHESIZE:
${sectionTexts.join('\n\n---\n\n')}

PROPERTY CONTEXT:
${brief.split('\n').slice(0, 10).join('\n')}

Return ONLY a valid HTML fragment (no wrapper tags, no markdown).`;
}

function buildClosingStatementPrompt(
  brief: string,
  triggerFlags: Record<string, string> | null,
): string {
  const flagLines = triggerFlags
    ? Object.entries(triggerFlags)
        .map(([k, v]) => `  ${k}: ${v}`)
        .join('\n')
    : '  (No trigger flags stored — use field record conditions)';

  return `You are writing the Closing Statement section of a forensic roofing inspection report.

${CONTRACTOR_LANE_POLICY}

Write a professional closing statement (2–3 paragraphs) for this forensic inspection report. The closing should:
- Affirm what the package documents (methodology, findings, repairability assessment)
- Reference the inspector's attestation and the completeness of the photographic record
- Conditionally include relevant notes based on trigger flags below:
  * If claim_posture = pre_claim: note this is a pre-submission forensic record
  * If discontinued_status = discontinued_verified: note the product identification result is on file
  * If interior_scope_present: note interior observations are documented in the package
  * If mitigation_performed: reference the documented temporary repair/mitigation

TRIGGER FLAGS:
${flagLines}

PROPERTY CONTEXT:
${brief.split('\n').slice(0, 10).join('\n')}

Return ONLY a valid HTML fragment (no wrapper tags, no markdown).`;
}

