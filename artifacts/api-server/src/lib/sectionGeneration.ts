// ---------------------------------------------------------------------------

function buildFieldBrief(
  inspection: Record<string, unknown>,
  children: {
    slopes?: Array<{
      label: string;
      areaSqft?: number | null;
      materialType?: string | null;
      damagePresent?: boolean | null;
      damageType?: string | null;
      pitchRise?: number | null;
      pitchRun?: number | null;
    }>;
    sidingFacets?: Array<{ label?: string; damageType?: string | null }>;
    damageInstances?: Array<{
      slopeId?: string | null;
      instanceType?: string | null;
      severityCategory?: string | null;
    }>;
    testSquares?: Array<{ label?: string }>;
    testSquareHits?: Array<{ hitType?: string | null }>;
    products?: Array<{
      brand?: string | null;
      productLine?: string | null;
      identificationMethod?: string | null;
      itelSampleRef?: string | null;
    }>;
    interiorObservations?: Array<{ location?: string; description?: string }>;
  },
): string {
  const lines: string[] = [];

  lines.push(`PROPERTY: ${inspection.insuredName ?? 'Unknown'}`);
  if (inspection.address) lines.push(`ADDRESS: ${inspection.address}`);
  if (inspection.claimNumber) lines.push(`CLAIM #: ${inspection.claimNumber}`);
  if (inspection.dateOfLoss) lines.push(`DATE OF LOSS: ${inspection.dateOfLoss}`);

  const storm = inspection.stormConfirmedRef as {
    type?: string;
    date?: string;
    hailSize?: number | null;
    windSpeed?: number | null;
    description?: string | null;
  } | null;
  if (storm) {
    lines.push(`STORM: ${storm.type ?? 'unknown'} on ${storm.date ?? 'unknown date'}`);
    if (storm.hailSize) lines.push(`  Hail size: ${storm.hailSize}"`);
    if (storm.windSpeed) lines.push(`  Wind speed: ${storm.windSpeed} mph`);
  }

  lines.push('');
  lines.push('DAMAGE FLAGS:');
  lines.push(`  Roof: ${inspection.roofDamageFound ? 'YES' : 'no'}`);
  lines.push(`  Siding: ${inspection.sidingDamageFound ? 'YES' : 'no'}`);
  lines.push(`  Collateral: ${inspection.collateralDamageFound ? 'YES' : 'no'}`);
  lines.push(`  Interior: ${inspection.interiorDamageFound ? 'YES' : 'no'}`);

  const slopes = children.slopes ?? [];
  if (slopes.length > 0) {
    lines.push('');
    lines.push('ROOF FACETS:');
    for (const s of slopes) {
      const parts: string[] = [`  ${s.label}`];
      if (s.areaSqft != null) parts.push(`${s.areaSqft.toFixed(1)} sqft`);
      if (s.materialType) parts.push(s.materialType);
      if (s.damagePresent) parts.push(`DAMAGED: ${s.damageType ?? 'type not specified'}`);
      lines.push(parts.join(' | '));
    }
  }

  const sidingFacets = children.sidingFacets ?? [];
  if (sidingFacets.length > 0) {
    lines.push('');
    lines.push('SIDING FACETS:');
    for (const sf of sidingFacets) {
      lines.push(`  ${sf.label ?? 'Facet'} — damage: ${sf.damageType ?? 'none'}`);
    }
  }

  const damageInstances = children.damageInstances ?? [];
  if (damageInstances.length > 0) {
    lines.push('');
    lines.push(`DAMAGE INSTANCES: ${damageInstances.length} documented`);
    const byType = new Map<string, number>();
    for (const d of damageInstances) {
      const t = d.instanceType ?? 'unknown';
      byType.set(t, (byType.get(t) ?? 0) + 1);
    }
    for (const [t, count] of byType) lines.push(`  ${t}: ${count}`);
  }

  const testSquares = children.testSquares ?? [];
  const testHits = children.testSquareHits ?? [];
  if (testSquares.length > 0) {
    lines.push('');
    lines.push(`TEST SQUARES: ${testSquares.length} square(s), ${testHits.length} total hit(s)`);
  }

  const products = children.products ?? [];
  if (products.length > 0) {
    lines.push('');
    lines.push('PRODUCT IDENTIFICATION:');
    for (const p of products) {
      const name = [p.brand, p.productLine].filter(Boolean).join(' ') || 'Unidentified';
      lines.push(`  ${name} — method: ${p.identificationMethod ?? 'not specified'}`);
      if (p.itelSampleRef) lines.push(`    ITEL sample: ${p.itelSampleRef}`);
    }
  }

  const interiorObs = children.interiorObservations ?? [];
  if (interiorObs.length > 0) {
    lines.push('');
    lines.push('INTERIOR / ATTIC OBSERVATIONS:');
    for (const obs of interiorObs) {
      if (obs.location || obs.description) {
        lines.push(`  ${obs.location ?? ''}: ${obs.description ?? ''}`);
      }
    }
  }

  const ra = inspection.repairabilityAssessment as StoredRepairabilityAssessment | null;
  if (ra) {
    lines.push('');
    lines.push('REPAIRABILITY ASSESSMENT:');
    if (ra.version === 2) {
      for (const system of ['roof', 'siding'] as const) {
        const flow = ra[system];
        if (!flow) continue;
        lines.push(`  ${system}: ${DETERMINATION_LABELS[flow.determination] ?? flow.determination}`);
      }
    } else if (ra.version === 3) {
      const v3 = ra as unknown as { warranted?: string };
      lines.push(`  Warranted: ${RAP_WARRANTED_LABELS[v3.warranted ?? ''] ?? v3.warranted}`);
      const rap = extractRap(ra);
      if (rap) {
        for (const line of rapScorecardBriefLines(computeRapScorecard(rap), rap.selection)) {
          lines.push(`  ${line}`);
        }
      }
    }
  }

  return lines.join('\n');
}

